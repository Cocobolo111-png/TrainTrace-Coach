import { test, expect } from "@playwright/test";
test("first setup opens an editable candidate directly and guidance remains optional", async ({ page }) => {
  const forbidden: string[] = [];
  page.on("request", (r) => { if (/api\/|deepseek/.test(r.url())) forbidden.push(r.url()); });
  await page.goto("/");
  await page.getByRole("button", { name: "跳过新手引导", exact: true }).click();
  await page.getByRole("button", { name: "准备好了，开始训练" }).click();
  await expect(page.getByRole("button", { name: "开始记录", exact: true })).toBeVisible();
  const plan = page.locator(".plan-exercise").first();
  await expect(plan.locator(".plan-adjustments")).not.toHaveAttribute("open");
  await expect(plan.locator(".action-guidance")).not.toHaveAttribute("open");
  await plan.locator(".plan-adjustments > summary").click();
  await plan.getByRole("button", { name: "替换动作" }).click();
  await plan.getByLabel("替换杠铃卧推").selectOption("chest-press");
  await plan.locator(".action-guidance > summary").click();
  await expect(plan.getByText("ACT-005", { exact: false })).toBeVisible();
  await expect(plan.getByRole("heading", { name: "动作要领", exact: true })).toBeVisible();
  await plan.locator(".action-guidance > summary").click();
  await page.getByRole("button", { name: "开始记录", exact: true }).click();
  await page.getByLabel("本组重量", { exact: true }).fill("10");
  await page.getByRole("button", { name: "完成第 1 组", exact: true }).click();
  await expect(page.getByRole("timer", { name: "组间休息" })).toBeVisible();
  await page.locator(".action-guidance > summary").click();
  await expect(page.getByRole("button", { name: "完成第 2 组", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator(".immersive-guide")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "继续未完成训练", exact: true })).toBeVisible();
  expect(forbidden).toEqual([]);
});
